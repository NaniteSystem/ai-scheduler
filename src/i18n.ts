const dicts: Record<Lang, Dict> = { en, ru, ja };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
  return s;
}

/** Hook: returns a `t(key, vars?)` translator bound to the current language. */
export function useT() {
  const lang = useStore((s) => s.lang);
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

/** Hook: returns the current app language. */
export function useLang(): Lang {
  return useStore((s) => s.lang);
}
