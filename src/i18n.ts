import { useStore } from './store';
import { ru as ruLocale, enUS as enLocale, ja as jaLocale } from 'date-fns/locale';
import type { Locale } from 'date-fns';

export type Lang = 'en' | 'ru' | 'ja';

/** date-fns locale for the current language (use as { locale } in format()). */
export function dateLocale(lang: Lang): Locale {
  return lang === 'ru' ? ruLocale : lang === 'ja' ? jaLocale : enLocale;
}

/** Hook returning the date-fns locale bound to current language. */
export function useDateLocale(): Locale {
  const lang = useStore((s) => s.lang);
  return dateLocale(lang);
}

